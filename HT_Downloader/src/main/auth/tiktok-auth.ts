import { BrowserWindow, session } from 'electron';
import path from 'node:path';
import fs from 'node:fs/promises';
import { logger } from '../utils/logger';

export class TikTokAuth {
  private loginWindow: BrowserWindow | null = null;
  private readonly cookiesPath: string;

  constructor(userDataPath: string) {
    this.cookiesPath = path.join(userDataPath, 'tiktok_cookies.txt');
  }

  getCookiesFilePath(): string {
    return this.cookiesPath;
  }

  async getLoginStatus(): Promise<{ loggedIn: boolean }> {
    try {
      const cookies = await session.defaultSession.cookies.get({ domain: '.tiktok.com' });
      const sessionCookie = cookies.find(c => (c.name === 'sessionid' || c.name === 'sid_tt') && c.value.length > 5);
      return { loggedIn: Boolean(sessionCookie) };
    } catch (err) {
      logger.warn('TIKTOK_STATUS_CHECK_FAILED', { error: String(err) });
      return { loggedIn: false };
    }
  }

  async openLoginWindow(): Promise<{ success: boolean }> {
    if (this.loginWindow && !this.loginWindow.isDestroyed()) {
      this.loginWindow.focus();
      return { success: false };
    }

    return new Promise(resolve => {
      this.loginWindow = new BrowserWindow({
        width: 600,
        height: 750,
        title: 'Đăng nhập TikTok - HT Downloader',
        autoHideMenuBar: true,
        webPreferences: {
          nodeIntegration: false,
          contextIsolation: true
        }
      });

      this.loginWindow.webContents.setUserAgent(
        'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'
      );

      void this.loginWindow.loadURL('https://www.tiktok.com/login');

      let resolved = false;
      const checkInterval = setInterval(async () => {
        try {
          const status = await this.getLoginStatus();
          if (status.loggedIn && !resolved) {
            resolved = true;
            clearInterval(checkInterval);
            logger.info('TIKTOK_LOGIN_DETECTED');
            await this.exportCookies();
            if (this.loginWindow && !this.loginWindow.isDestroyed()) {
              this.loginWindow.close();
            }
            resolve({ success: true });
          }
        } catch {
          // Ignore polling errors
        }
      }, 1500);

      this.loginWindow.on('closed', () => {
        clearInterval(checkInterval);
        this.loginWindow = null;
        if (!resolved) {
          resolve({ success: false });
        }
      });
    });
  }

  async logout(): Promise<boolean> {
    try {
      const cookies = await session.defaultSession.cookies.get({ domain: '.tiktok.com' });
      for (const cookie of cookies) {
        const protocol = cookie.secure ? 'https://' : 'http://';
        const rawDomain = cookie.domain || 'tiktok.com';
        const domain = rawDomain.replace(/^\./, '');
        const url = `${protocol}${domain}${cookie.path}`;
        await session.defaultSession.cookies.remove(url, cookie.name);
      }
      try {
        await fs.unlink(this.cookiesPath);
      } catch {
        // File may not exist
      }
      logger.info('TIKTOK_LOGOUT_SUCCESS');
      return true;
    } catch (err) {
      logger.warn('TIKTOK_LOGOUT_FAILED', { error: String(err) });
      return false;
    }
  }

  async exportCookies(): Promise<string | null> {
    try {
      const cookies = await session.defaultSession.cookies.get({ domain: '.tiktok.com' });
      if (!cookies.length) return null;

      let fileContent = '# Netscape HTTP Cookie File\n# Generated by HT Downloader\n\n';
      for (const c of cookies) {
        const domain = c.domain || '.tiktok.com';
        const includeSub = domain.startsWith('.') ? 'TRUE' : 'FALSE';
        const cookiePath = c.path || '/';
        const secure = c.secure ? 'TRUE' : 'FALSE';
        const expires = c.expirationDate ? Math.floor(c.expirationDate) : Math.floor(Date.now() / 1000) + 86400 * 30;
        fileContent += `${domain}\t${includeSub}\t${cookiePath}\t${secure}\t${expires}\t${c.name}\t${c.value}\n`;
      }

      await fs.writeFile(this.cookiesPath, fileContent, 'utf8');
      return this.cookiesPath;
    } catch (err) {
      logger.warn('TIKTOK_COOKIE_EXPORT_FAILED', { error: String(err) });
      return null;
    }
  }
}
